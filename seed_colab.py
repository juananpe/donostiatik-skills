"""## 8 · Ejecutar seed

Genera embeddings vía OpenRouter y los inserta en ChromaDB.

- **Preguntas:** se indexan por el texto de la pregunta.
- **Respuestas:** se indexan por la **pregunta asociada** (no por la respuesta), para que al buscar por similitud semántica con una consulta ciudadana se encuentre la respuesta modelo.
"""

import logging

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s - %(message)s")
log = logging.getLogger("seed")


async def run_seed() -> None:
    # 1) Preguntas históricas
    log.info("Generando embeddings de %d preguntas históricas...", len(PREGUNTAS_HISTORICAS))
    ids = [q[0] for q in PREGUNTAS_HISTORICAS]
    docs = [q[1] for q in PREGUNTAS_HISTORICAS]
    metas = [q[2] for q in PREGUNTAS_HISTORICAS]
    vecs = await embed(docs)
    add_items(COL_PREGUNTAS, ids, docs, vecs, metas)
    log.info("✅ Insertadas %d preguntas en '%s'.", len(ids), COL_PREGUNTAS)

    # 2) Respuestas históricas: indexamos por la PREGUNTA (para buscar por similitud
    # a la consulta entrante) y guardamos la RESPUESTA en el campo documento +
    # la pregunta en metadata para que el LLM pueda usarlas.
    log.info("Generando embeddings de %d respuestas históricas...", len(RESPUESTAS_HISTORICAS))
    ids_r = [r[0] for r in RESPUESTAS_HISTORICAS]
    preguntas_r = [r[1] for r in RESPUESTAS_HISTORICAS]
    respuestas_r = [r[2] for r in RESPUESTAS_HISTORICAS]
    metas_r = [{**r[3], "pregunta": r[1]} for r in RESPUESTAS_HISTORICAS]
    # Embedding basado en la PREGUNTA, no en la respuesta
    vecs_r = await embed(preguntas_r)
    add_items(COL_RESPUESTAS, ids_r, respuestas_r, vecs_r, metas_r)
    log.info("✅ Insertadas %d respuestas en '%s'.", len(ids_r), COL_RESPUESTAS)

    log.info("🎉 Seed completado.")


await run_seed()

"""## 9 · Verificar resultados

Haz una consulta de prueba para comprobar que la búsqueda por similitud funciona.
"""

def query_similar(
    collection_name: str,
    query_embedding: list[float],
    n_results: int = 5,
) -> list[dict]:
    """Consulta una colección y normaliza el resultado."""
    col = get_collection(collection_name)
    res = col.query(query_embeddings=[query_embedding], n_results=n_results)

    ids = res.get("ids", [[]])[0]
    docs = res.get("documents", [[]])[0]
    metas = res.get("metadatas", [[]])[0] or [{} for _ in ids]
    distancias = res.get("distances", [[]])[0]

    out = []
    for i, doc_id in enumerate(ids):
        dist = distancias[i] if i < len(distancias) else 1.0
        sim = max(0.0, min(1.0, 1.0 - dist))
        out.append({
            "id": doc_id,
            "documento": docs[i] if i < len(docs) else "",
            "metadata": metas[i] if i < len(metas) else {},
            "similitud": sim,
        })
    return out


