"""## 4 · Cliente de embeddings (OpenRouter via OpenAI SDK)

OpenRouter expone un endpoint compatible con el SDK de OpenAI.
"""

import asyncio
from openai import AsyncOpenAI

# Cliente OpenAI-compatible apuntando a OpenRouter
embeddings_client = AsyncOpenAI(
    base_url=OPENROUTER_BASE_URL,
    api_key=OPENROUTER_API_KEY,
)


async def embed(texts: list[str]) -> list[list[float]]:
    """Devuelve embeddings para una lista de textos vía OpenRouter."""
    resp = await embeddings_client.embeddings.create(
        model=EMBEDDING_MODEL,
        input=texts,
    )
    return [item.embedding for item in resp.data]


async def embed_one(text: str) -> list[float]:
    """Embedding de un solo texto."""
    (vec,) = await embed([text])
    return vec


# Test rápido
test_vec = await embed_one("Hola mundo")
print(f"✅ Embeddings OK — dimensión: {len(test_vec)}")

"""## 5 · ChromaDB (en memoria o persistente)

ChromaDB en modo `persistent` guarda los datos en `CHROMA_PERSIST_DIR`
"""

import chromadb
from chromadb.config import Settings as ChromaSettings

# Colecciones
COL_PREGUNTAS = "preguntas_historicas"
COL_RESPUESTAS = "respuestas_historicas"


def get_chroma_client() -> chromadb.ClientAPI:
    if CHROMA_MODE == "persistent":
        return chromadb.PersistentClient(
            path=CHROMA_PERSIST_DIR,
            settings=ChromaSettings(anonymized_telemetry=False, allow_reset=True),
        )
    else:
        return chromadb.EphemeralClient(
            settings=ChromaSettings(anonymized_telemetry=False, allow_reset=True),
        )


chroma_client = get_chroma_client()


def get_collection(name: str) -> chromadb.Collection:
    return chroma_client.get_or_create_collection(
        name=name, metadata={"hnsw:space": "cosine"}
    )


def add_items(
    collection_name: str,
    ids: list[str],
    documents: list[str],
    embeddings: list[list[float]],
    metadatas: list[dict] | None = None,
) -> None:
    """Inserta/actualiza items en una colección de ChromaDB."""
    col = get_collection(collection_name)
    col.upsert(
        ids=ids,
        documents=documents,
        embeddings=embeddings,
        metadatas=metadatas or [{} for _ in ids],
    )


