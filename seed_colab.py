OPENROUTER_BASE_URL = "https://openrouter.ai/api/v1"

# Modelo de embeddings vía OpenRouter (OpenAI-compatible)
# Options: "openai/text-embedding-3-large" (3072d) o "openai/text-embedding-3-small" (1536d)
EMBEDDING_MODEL = "openai/text-embedding-3-large"

# ChromaDB: "memory" para ephemeral, o "persistent" para guardar en disco
CHROMA_MODE = "persistent"  # "memory" | "persistent"
CHROMA_PERSIST_DIR = "./chroma_db"  # carpeta local si mode=persistent

print(f"📦 Embeddings: {EMBEDDING_MODEL}")
